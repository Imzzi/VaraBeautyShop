import fs from 'node:fs';
import path from 'node:path';

const root = process.cwd();
const distHtmlPath = path.resolve(root, 'dist', 'index.html');
const fallbackHtmlPath = path.resolve(root, 'index.html');
const sourcePath = fs.existsSync(distHtmlPath) ? distHtmlPath : fallbackHtmlPath;

if (!fs.existsSync(sourcePath)) {
  console.error(`embed-index-html: Neither ${distHtmlPath} nor ${fallbackHtmlPath} exists.`);
  process.exit(1);
}

const html = fs.readFileSync(sourcePath, 'utf8');
if (!html.includes('</head>') || !html.includes('</body>')) {
  console.error(`embed-index-html: ${sourcePath} is missing </head> or </body>.`);
  process.exit(1);
}

const outDir = path.resolve(root, 'src', 'generated');
fs.mkdirSync(outDir, { recursive: true });
const outPath = path.resolve(outDir, 'indexHtmlTemplate.ts');
const content = `// Auto-generated by scripts/embed-index-html.mjs — do not edit manually.\nexport const BUILT_INDEX_HTML: string = ${JSON.stringify(html)};\n`;
fs.writeFileSync(outPath, content, 'utf8');
console.log(`Embedded HTML template from ${path.relative(root, sourcePath)} -> ${path.relative(root, outPath)} (${html.length} chars)`);
